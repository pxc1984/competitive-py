# ## Задача 5. Теоремы Муавра–Лапласа и Пуассона

# %% [markdown]
# ### Теория
#
# **1. Схема Бернулли.** $n$ независимых испытаний, в каждом успех с вероятностью $p$, $q=1-p$. Число успехов $\xi\sim\mathrm{Bin}(n,p)$ есть сумма индикаторов: $\xi=I_1+\dots+I_n$. Для индикатора $EI_j=EI_j^2=p$, поэтому $\operatorname{Var}I_j=p-p^2=pq$. Матожидания складываются всегда, дисперсии — для независимых слагаемых:
#
# $$E\xi=np,\qquad \operatorname{Var}\xi=npq,\qquad \sigma=\sqrt{npq}.$$
#
# Стандартизованная точка: $x_k=\dfrac{k-np}{\sqrt{npq}}$. При большом $npq$ распределение $\xi$ близко к $N(np,\,npq)$ — это и утверждают теоремы Муавра–Лапласа.
#
# **2. Локальная теорема (вероятность одной точки).**
#
# $$P(\xi=k)\approx\frac{1}{\sqrt{npq}}\,\varphi(x_k).$$
#
# Откуда $1/\sqrt{npq}$: значения $\xi$ стоят с шагом 1, поэтому вероятность точки ≈ плотность $N(np,\sigma^2)$ в точке $k$, умноженная на шаг 1. А эта плотность равна $\frac1\sigma\varphi\big(\frac{x-np}{\sigma}\big)$: растянув кривую по горизонтали в $\sigma$ раз, её надо сжать по вертикали в $\sigma$ раз, чтобы площадь осталась 1.
#
# **3. Интегральная теорема (промежуток) и поправка на непрерывность.** Для целых $a\le b$
#
# $$P(a\le\xi\le b)\approx\Phi\!\left(\frac{b+0{,}5-np}{\sqrt{npq}}\right)-\Phi\!\left(\frac{a-0{,}5-np}{\sqrt{npq}}\right).$$
#
# Почему $\pm0{,}5$: каждое целое $k$ «владеет» под кривой полосой $[k-0{,}5;\,k+0{,}5]$. Без поправки (как в формулировке теоремы) ответ тоже законен, но теряются половины двух крайних столбиков; при малом $\sigma$ это заметно.
#
# Для дискретной $\xi$ строгое и нестрогое неравенства — **разные** события: $P(\xi>k)=P(\xi\ge k+1)$. Поэтому сначала запиши событие как «от $a$ до $b$ включительно» с целыми концами, потом ставь поправку. Хвост — частный случай: $P(\xi\ge a)\approx1-\Phi\big(\frac{a-0{,}5-np}{\sqrt{npq}}\big)$.
#
# Плотность $\varphi$ чётна, поэтому $\Phi(-x)=\int_x^{\infty}\varphi=1-\Phi(x)$. Для промежутка, симметричного относительно $np$:
#
# $$P(|\xi-np|\le t)\approx2\Phi\!\left(\frac{t+0{,}5}{\sqrt{npq}}\right)-1.$$
#
# Если в таблице функция Лапласа $\Phi_0=\Phi-\frac12$, то $2\Phi(x)-1=2\Phi_0(x)$.
#
# **4. Теорема Пуассона (редкие события).** Если $n$ велико, $p$ мало, а $\lambda=np$ порядка единиц, то
#
# $$P(\xi=k)\approx\frac{\lambda^k}{k!}e^{-\lambda},\qquad k=0,1,2,\dots$$
#
# Ошибка для вероятности любого события не больше $np^2$. Если мало $q$, приближают так же число неудач $n-\xi$.
#
# **5. Как выбрать приближение** (по $npq$ и $p$).
# - $npq\gtrsim10$ — Муавр–Лаплас: точка — локальная теорема, промежуток — интегральная.
# - $p$ мало, а $\lambda=np$ порядка единиц — Пуассон. Распределение тут прижато к нулю и несимметрично — кривая Гаусса описывает его плохо.
#
# **Значения для задачи:** $\Phi(1{,}25)\approx0{,}8944$, $\varphi(0{,}5)\approx0{,}3521$, $e^{-2}\approx0{,}1353$.

# %% [markdown]
# ### Условие
#
# Интернет-магазин за день отправляет $400$ посылок. Каждая посылка независимо от остальных доставляется позже обещанного срока с вероятностью $0{,}1$.
#
# 1. Оцени вероятность того, что число опоздавших посылок будет от $33$ до $47$ включительно.
# 2. Оцени вероятность того, что опоздают ровно $43$ посылки.
# 3. Кроме того, каждая посылка независимо повреждается в пути с вероятностью $0{,}005$. Какое приближение уместно для числа повреждённых посылок? Оцени вероятность того, что повреждённых будет больше одной, и укажи погрешность.

# %% [markdown]
# ### Решение
#
# **Шаг 1. Параметры.** Число опоздавших $\xi\sim\mathrm{Bin}(400;\,0{,}1)$:
#
# $$np=40,\qquad npq=400\cdot0{,}1\cdot0{,}9=36,\qquad\sigma=6.$$
#
# $npq=36\ge10$, значит, для пунктов 1–2 годится Муавр–Лаплас.
#
# **Шаг 2. Промежуток (интегральная теорема с поправкой).** Целые от $33$ до $47$ занимают отрезок $[32{,}5;\,47{,}5]$, симметричный относительно $40$, поэтому $x_\pm=\pm7{,}5/6=\pm1{,}25$ и
#
# $$P(33\le\xi\le47)\approx\Phi(1{,}25)-\Phi(-1{,}25)=2\Phi(1{,}25)-1\approx2\cdot0{,}8944-1\approx0{,}789.$$
#
# **Шаг 3. Точка (локальная теорема).** $x_{43}=\frac{43-40}{6}=0{,}5$, поэтому
#
# $$P(\xi=43)\approx\frac{\varphi(0{,}5)}{6}\approx\frac{0{,}3521}{6}\approx0{,}0587.$$
#
# **Шаг 4. Выбор приближения для повреждений.** Число повреждённых $\eta\sim\mathrm{Bin}(400;\,0{,}005)$. Здесь $npq\approx1{,}99$ — слишком мало для Муавра–Лапласа, зато $p$ мало и $\lambda=np=2$. Берём Пуассона; погрешность не больше $np^2=400\cdot0{,}005^2=0{,}01$.
#
# **Шаг 5. Вероятность.** Для целой $\eta$ «больше одной» значит $\eta\ge2$; удобнее через дополнение $\{\eta\le1\}$:
#
# $$P(\eta>1)=1-P(\eta=0)-P(\eta=1)\approx1-e^{-2}(1+2)\approx1-3\cdot0{,}1353\approx0{,}594.$$

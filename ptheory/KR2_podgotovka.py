# ## Задача 1. Смесь дискретных распределений

# %% [markdown]
# ### Теория
#
# **1. Дискретная величина.** Ряд распределения — значения $x_k$ (носитель) и вероятности $P(X=x_k)$; нормировка $\sum_k P(X=x_k)=1$ — лучшая проверка счёта. Функция распределения
#
# $$F_X(x)=P(X\le x)=\sum_{k:\;x_k\le x}P(X=x_k)
# $$
#
# ступенчатая: между точками носителя постоянна, в $x_k$ прыгает на $P(X=x_k)$, непрерывна справа. Отсюда $P(a<X\le b)=F(b)-F(a)$. Моменты: $E\,g(X)=\sum_k g(x_k)P(X=x_k)$, $\operatorname{Var}X=EX^2-(EX)^2$.
#
# **2. Смесь распределений.** Сначала случайно выбирается сценарий $T$ (с вероятностями $w_i$), при сценарии $i$ у $X$ своё распределение — компонента смеси. События $\{T=i\}$ образуют полную группу, поэтому по формуле полной вероятности
#
# $$P(X=k)=\sum_i w_i\,P(X=k\mid T=i).
# $$
#
# - Носитель $X$ — объединение носителей компонент. Если $k$ вне носителя компоненты, её слагаемое равно нулю: сначала выясни, какие сценарии дают данное $k$.
# - Нормировка выполняется сама: сумма по $k$ даёт $\sum_i w_i\cdot1=1$.
# - При бесконечном носителе (Пуассон, геометрическое) таблицу не выписать — ответ пишут формулой по $k$.
# - Так же складываются функции распределения и хвосты: $F_X=\sum_i w_iF_i$.
#
# **3. Матожидание смеси.** Подставим ряд и поменяем порядок суммирования (законно при абсолютной сходимости):
#
# $$EX=\sum_k k\sum_i w_iP(X=k\mid T=i)=\sum_i w_i\sum_k k\,P(X=k\mid T=i)=\sum_i w_i\,E[X\mid T=i].$$
#
# Здесь $E[X\mid T=i]$ — среднее $i$-й компоненты; ряд смеси не нужен. Так же усредняется $EX^2$, через него и считают $\operatorname{Var}X$ — **не** как среднее дисперсий компонент (см. углубление).
#
# **4. Ловушка: смесь — не линейная комбинация.** Смесь $Y_1\equiv0$ и $Y_2\equiv10$ с весами по $\tfrac12$ принимает значения $0$ и $10$, а $\tfrac12Y_1+\tfrac12Y_2\equiv5$: средние совпадают (в $EX$ ошибку не заметить), носители и дисперсии — нет.
#
# **5. Обратный вопрос (Байес).** По определению условной вероятности числитель — $P(T=i,\,X\in A)$, то есть слагаемое формулы полной вероятности, знаменатель — вся сумма:
#
# $$P(T=i\mid X\in A)=\frac{w_i\,P(X\in A\mid T=i)}{\sum_j w_j\,P(X\in A\mid T=j)}.
# $$
#
# **6. Моменты компонент (выводим сами).**
#
# - *Биномиальное* $\mathrm{Bin}(n,p)$: число успехов — сумма индикаторов успеха в испытаниях, $EI_j=1\cdot p+0\cdot q=p$, и по линейности $EX=EI_1+\dots+EI_n=np$.
# - *Геометрическое* (число неудач до первого успеха, $P(X=k)=pq^k,\ k\ge0$). Хвост $P(X\ge k)=q^k$: первые $k$ испытаний неудачны. Для $EX$ дифференцируем прогрессию почленно (при $|q|<1$ это законно):
#
# $$EX=\sum_{k\ge0}k\,pq^k=pq\sum_{k\ge1}kq^{k-1}=pq\Big(\sum_{k\ge0}q^k\Big)'=pq\Big(\frac{1}{1-q}\Big)'=\frac{pq}{(1-q)^2}=\frac{q}{p}.$$

# %% [markdown]
# ### Условие
#
# Такси предлагает заказ водителям по очереди, пока кто-нибудь не согласится. При данном времени суток водители решают независимо друг от друга и соглашаются с одной и той же вероятностью: в час пик — $\tfrac13$, в остальное время — $\tfrac34$. Случайный заказ сделан в час пик с вероятностью $\tfrac14$. $X$ — число водителей, отказавшихся от этого заказа.
#
# 1. Найди среднее число отказов $EX$.
# 2. Найди $P(X=m)$ для всех $m$ и функцию распределения $F_X(x)$. Чему равно $F_X(1{,}5)$?
# 3. Аналитик предлагает модель попроще: «$X$ — геометрическая с усреднённой вероятностью согласия $\bar p=\tfrac14\cdot\tfrac13+\tfrac34\cdot\tfrac34$». Сравни её матожидание с $EX$ и объясни расхождение.
# 4. Заказу отказали хотя бы двое. С какой вероятностью он сделан в час пик?

# %% [markdown]
# ### Решение
#
# **Шаг 1. Сценарии.** $T=1$ — час пик, $T=2$ — обычное время; $w_1=\tfrac14,\ w_2=\tfrac34$. При данном $T$ водители — независимые испытания с одной вероятностью успеха, $X$ — число неудач до первого успеха, то есть геометрическая величина: $p_1=\tfrac13,\ q_1=\tfrac23$ или $p_2=\tfrac34,\ q_2=\tfrac14$.
#
# **Шаг 2. Среднее** — по полному матожиданию (п. 3) и $E=q/p$ (п. 6):
#
# $$EX=\tfrac14\cdot\frac{2/3}{1/3}+\tfrac34\cdot\frac{1/4}{3/4}=\tfrac14\cdot2+\tfrac34\cdot\tfrac13=\tfrac34.$$
#
# **Шаг 3. Ряд и функция распределения.** Обе компоненты дают вклад при каждом $m\ge0$, поэтому ответ — формула:
#
# $$P(X=m)=\tfrac14\cdot\tfrac13\big(\tfrac23\big)^m+\tfrac34\cdot\tfrac34\big(\tfrac14\big)^m=\tfrac1{12}\big(\tfrac23\big)^m+\tfrac9{16}\big(\tfrac14\big)^m.$$
#
# Для $F_X$ удобнее хвосты: у компонент $P(X\ge k)=q_i^k$, значит $P(X\ge k)=\tfrac14\big(\tfrac23\big)^k+\tfrac34\big(\tfrac14\big)^k$. Так как $X$ целая, событие $X\le x$ — это «не $X\ge\lfloor x\rfloor+1$»:
#
# $$F_X(x)=\begin{cases}0, & x<0,\\ 1-\tfrac14\big(\tfrac23\big)^{\lfloor x\rfloor+1}-\tfrac34\big(\tfrac14\big)^{\lfloor x\rfloor+1}, & x\ge0.\end{cases}$$
#
# Между целыми $F_X$ постоянна, поэтому
#
# $$F_X(1{,}5)=F_X(1)=1-\Big(\tfrac14\cdot\tfrac49+\tfrac34\cdot\tfrac1{16}\Big)=1-\Big(\tfrac19+\tfrac3{64}\Big)=1-\tfrac{91}{576}=\tfrac{485}{576}\approx0{,}842.$$
#
# **Шаг 4. Модель аналитика.** $\bar p=\tfrac1{12}+\tfrac9{16}=\tfrac{31}{48}$, и у геометрической с таким параметром $E=\frac{1-\bar p}{\bar p}=\tfrac{17}{31}\approx0{,}548<\tfrac34$. Усреднять можно матожидания $q_i/p_i$ (п. 3), но не параметр (п. 4): функция $1/p-1$ нелинейна, при малых $p$ она резко растёт. Более того, $X$ не геометрическая ни при каком параметре: у геометрической он равен $P(X=0)$, то есть был бы $\tfrac{31}{48}=\bar p$, а этот вариант уже отвергнут.
#
# **Шаг 5. Байес** (п. 5). Знаменатель $P(X\ge2)=\tfrac{91}{576}$ — из шага 3, числитель — его слагаемое от часа пика:
#
# $$P(\text{пик}\mid X\ge2)=\frac{\tfrac14\cdot\tfrac49}{91/576}=\frac{64/576}{91/576}=\tfrac{64}{91}\approx0{,}703.$$
#
# Было $\tfrac14$: много отказов — сильный довод за час пик.


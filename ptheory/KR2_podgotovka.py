# ## Задача 2. Функция от непрерывной случайной величины: плотность, моменты, ковариация

# %% [markdown]
# ### Теория
#
# Пусть у $\xi$ есть плотность $\rho_\xi$, а $\eta=g(\xi)$.
#
# **1. LOTUS.** Для среднего функции плотность самой функции не нужна (если интеграл сходится абсолютно):
#
# $$
# E\,g(\xi)=\int_{-\infty}^{\infty}g(x)\,\rho_\xi(x)\,dx.
# $$
#
# Отсюда дисперсия и ковариация:
#
# $$
# \operatorname{Var}\eta=E\eta^2-(E\eta)^2,\qquad \operatorname{cov}(\xi,\eta)=E[\xi\eta]-E\xi\cdot E\eta.
# $$
#
# Величины $\eta^2$ и $\xi\eta$ — тоже функции одной $\xi$, так что совместная плотность не нужна. Второй способ — найти плотность $\eta$ (п. 2) и интегрировать по ней. Ответы обязаны совпасть.
#
# **2. Плотность $\eta$: метод функции распределения.** Найди множество значений $\eta$ (вне него функция распределения равна 0 или 1). Затем перепиши событие «$\eta\le y$» как событие про $\xi$, посчитай его вероятность и продифференцируй по $y$. Для строго монотонной $g$ с обратной функцией $h$:
#
# $$
# F_\eta(y)=\begin{cases}F_\xi(h(y)), & g \text{ возрастает},\\ 1-F_\xi(h(y)), & g \text{ убывает},\end{cases}\qquad \rho_\eta(y)=\rho_\xi(h(y))\,|h'(y)|.
# $$
#
# Убывающая функция **переворачивает неравенство**: «$g(\xi)\le y$» означает «$\xi\ge h(y)$». Отсюда и модуль: производная обратной функции отрицательна, но перед ней стоит минус из «1 − F». Строгое и нестрогое неравенства для непрерывной величины дают одну вероятность.
#
# **3. Некоррелированность ≠ независимость.** Независимые величины некоррелированы, поэтому ненулевая ковариация доказывает зависимость. Обратное неверно. Пусть точка $(X,Y)$ равномерна в ромбе $|x|+|y|\le1$. По симметрии ромба ковариация равна нулю. Но величины зависимы: точка $(0{,}6;\,0{,}6)$ лежит вне ромба, поэтому событие «обе координаты больше 0,6» невозможно, хотя каждая координата по отдельности бывает больше 0,6.

# %% [markdown]
# ### Условие
#
# Время ответа сервера $\xi$ (в секундах) имеет плотность
#
# $$
# \rho_\xi(x)=\frac{3}{(1+x)^4}\ \text{ при } x\ge0,\qquad \rho_\xi(x)=0\ \text{ при } x<0.
# $$
#
# Система мониторинга пересчитывает время в «индекс отзывчивости» $\eta=\dfrac{1}{1+\xi}$: индекс равен 1 при мгновенном ответе и близок к нулю при долгом. Запрос называют комфортным, если индекс больше времени ответа в секундах. Найди:
# 1. функцию распределения и плотность индекса;
# 2. вероятность того, что запрос комфортный;
# 3. среднее индекса двумя способами (через плотность $\xi$ и через плотность индекса) и его дисперсию;
# 4. среднее время ответа и ковариацию времени и индекса. Объясни её знак до вычислений.

# %% [markdown]
# ### Решение
#
# **Шаг 1. Хвост $\xi$.** При $t\ge0$
#
# $$
# P(\xi>t)=\int_t^\infty\frac{3\,dx}{(1+x)^4}=\Big[-\frac{1}{(1+x)^3}\Big]_t^\infty=\frac{1}{(1+t)^3}.
# $$
#
# При $t=0$ получаем 1 — нормировка выполнена.
#
# **Шаг 2. Распределение индекса.** Индекс принимает значения из $(0,1]$, функция $1/(1+x)$ убывает, поэтому неравенство переворачивается. При $0<y\le1$ порог $1/y-1$ неотрицателен, и формула шага 1 применима:
#
# $$
# F_\eta(y)=P\Big(\frac{1}{1+\xi}\le y\Big)=P\Big(\xi\ge\frac1y-1\Big)=\frac{1}{(1/y)^3}=y^3,\qquad \rho_\eta(y)=3y^2.
# $$
#
# **Шаг 3. Комфортный запрос.** Нужно событие $\eta>\xi$. На носителе $1+\xi>0$, поэтому умножаем без смены знака:
#
# $$
# \frac{1}{1+\xi}>\xi\iff\xi^2+\xi-1<0\iff0\le\xi<x_0=\frac{\sqrt5-1}{2}\approx0{,}618.
# $$
#
# По шагу 1 вероятность равна $1-(1+x_0)^{-3}$, а в корне $x_0$ неравенство обращается в равенство: $(1+x_0)^{-1}=x_0$. Понижаем степень через $x_0^2=1-x_0$:
#
# $$
# x_0^3=x_0-x_0^2=2x_0-1=\sqrt5-2,\qquad P(\eta>\xi)=1-x_0^3=3-\sqrt5\approx0{,}764.
# $$
#
# **Шаг 4. Среднее и дисперсия индекса.** Используем $\int_0^\infty(1+x)^{-k}dx=\frac{1}{k-1}$ при $k>1$. Слева LOTUS, справа плотность из шага 2:
#
# $$
# E\eta=\int_0^\infty\frac{3\,dx}{(1+x)^5}=\frac34=\int_0^1y\cdot3y^2\,dy,\qquad E\eta^2=\int_0^\infty\frac{3\,dx}{(1+x)^6}=\frac35=\int_0^13y^4\,dy,
# $$
#
# $$
# \operatorname{Var}\eta=\frac35-\frac{9}{16}=\frac{3}{80}.
# $$
#
# **Шаг 5. Ковариация.** Функция убывает, поэтому ждём отрицательный ответ. Среднее $\xi$ удобно найти LOTUS «в обратную сторону»: $\xi=1/\eta-1$ — функция индекса, а его плотность известна. Произведение интеграла не требует: $\xi\eta=\frac{(1+\xi)-1}{1+\xi}=1-\eta$. Поэтому
#
# $$
# E\xi=\int_0^1\Big(\frac1y-1\Big)3y^2\,dy=\frac12,\qquad \operatorname{cov}(\xi,\eta)=\Big(1-\frac34\Big)-\frac12\cdot\frac34=-\frac18.
# $$

# %% [markdown]
# ## Задача 3. Двумерная плотность: маргиналы, ковариация, (не)зависимость

# %% [markdown]
# ### Теория
#
# **1. Плотность вектора.** $\rho(x,y)\ge0$ — плотность вектора $(\xi,\eta)$, если для любой области $D$
#
# $$P\big((\xi,\eta)\in D\big)=\iint_D \rho(x,y)\,dx\,dy .
# $$
#
# При $D=\mathbb R^2$ — нормировка $\iint\rho=1$. Интегрировать достаточно по части $D$, где $\rho>0$ (носитель); отсюда и пределы.
#
# **2. Повторный интеграл и пределы.** Внешняя переменная пробегает проекцию области на ось, внутренняя — от входа вертикальной прямой в область до выхода; эти пределы зависят от $x$ (постоянны только у прямоугольника). Для треугольника $T_a=\{x\ge0,\ y\ge0,\ x+y\le a\}$ проекция — $[0,a]$, вход на оси абсцисс, выход на гипотенузе $y=a-x$:
#
# $$\iint_{T_a}h\,dx\,dy=\int_0^a\Big(\int_0^{a-x}h(x,y)\,dy\Big)dx .$$
#
# **3. Маргинальные плотности:** $\rho_\xi(x)=\int\rho(x,y)\,dy,\ \rho_\eta(y)=\int\rho(x,y)\,dx$ — интегрируем по сечению носителя. Обязательно укажи, где маргинал положителен (вне — ноль).
#
# **4. Независимость и факторизационный признак.** $\xi,\eta$ независимы $\iff\rho(x,y)=\rho_\xi(x)\rho_\eta(y)$ (почти всюду).
#
# **5. Быстрый тест на зависимость.** У независимого вектора носитель — «прямоугольник» $\{\rho_\xi>0\}\times\{\rho_\eta>0\}$. Найди множества $A,B$ с $P(\xi\in A)>0,\ P(\eta\in B)>0$, но $A\times B$ вне носителя. Тогда $P(\xi\in A,\eta\in B)=0\ne P(\xi\in A)\,P(\eta\in B)$: компоненты зависимы.
#
# Итак, для независимости нужны **и** формула-произведение, **и** носитель-прямоугольник. Нефакторизуемая формула (скажем, $x+y$) даёт зависимость и на прямоугольнике; там ищи $\operatorname{cov}\ne0$ (п. 6).
#
# **6. Ковариация.**
#
# $$E\,h(\xi,\eta)=\iint h(x,y)\,\rho(x,y)\,dx\,dy,\qquad \operatorname{cov}(\xi,\eta)=E[\xi\eta]-E\xi\,E\eta .
# $$
#
# При независимости двойной интеграл распадается: $E[\xi\eta]=\iint xy\,\rho_\xi\rho_\eta=\int x\rho_\xi\,dx\cdot\int y\rho_\eta\,dy=E\xi\,E\eta$. Значит, независимы $\Rightarrow\operatorname{cov}=0$, а $\operatorname{cov}\ne0\Rightarrow$ зависимы. Но $\operatorname{cov}=0$ независимости не гарантирует.

# %% [markdown]
# ### Условие
#
# Случайно выбранный слиток экспериментального сплава состоит из меди, никеля и цинка: $\xi$ — доля меди, $\eta$ — доля никеля (по массе), остальное — цинк. Совместная плотность вектора $(\xi,\eta)$:
#
# $$\rho(x,y)=\begin{cases}c\,xy, & x\ge0,\ y\ge0,\ x+y\le1,\\ 0, & \text{иначе.}\end{cases}$$
#
# 1. Найди $c$ и маргинальную плотность $\rho_\xi(x)$ доли меди. Как выглядит $\rho_\eta(y)$?
# 2. Найди вероятность того, что цинк составляет больше половины массы слитка.
# 3. Найди $\operatorname{cov}(\xi,\eta)$ и объясни её знак.
# 4. Технолог: «Плотность $c\,xy$ — это $f(x)\,g(y)$, значит, доли независимы». Прав ли он?

# %% [markdown]
# ### Решение
#
# **Шаг 1. Маргинал и $c$.** Носитель — треугольник $T_1$; при $x\in[0,1]$ его сечение — $0\le y\le1-x$ (п. 2 теории):
#
# $$\rho_\xi(x)=\int_0^{1-x}c\,xy\,dy=c\,x\cdot\frac{y^2}{2}\Big|_0^{1-x}=\frac c2\,x(1-x)^2 .$$
#
# Нормировка: $\iint\rho=\int_0^1\rho_\xi\,dx=1$; раскрываем скобки:
#
# $$\frac c2\int_0^1\big(x-2x^2+x^3\big)\,dx=\frac c2\Big(\frac12-\frac23+\frac14\Big)=\frac c2\cdot\frac1{12}=1\ \Rightarrow\ c=24 .$$
#
# Значит, $\rho_\xi(x)=12x(1-x)^2$ при $x\in[0,1]$, вне — ноль. Формула и треугольник симметричны относительно $x\leftrightarrow y$, поэтому $\rho_\eta(y)=12y(1-y)^2,\ y\in[0,1]$.
#
# **Шаг 2. Вероятность.** Цинка больше половины $\iff 1-\xi-\eta>\frac12\iff\xi+\eta<\frac12$ — треугольник $T_{1/2}$ (п. 2 теории). Замена $x=\frac t2,\ dx=\frac{dt}2,\ \frac12-x=\frac{1-t}2$ даёт множитель $\frac1{16}$ и сводит интеграл к шагу 1:
#
# $$P=\int_0^{1/2}\!\!\int_0^{1/2-x}24xy\,dy\,dx=12\int_0^{1/2}x\Big(\frac12-x\Big)^2dx=\frac{12}{16}\int_0^1t(1-t)^2\,dt=\frac{12}{16}\cdot\frac1{12}=\frac1{16}.$$
#
# **Шаг 3. Ковариация.** По маргиналу и симметрии:
#
# $$E\xi=E\eta=12\int_0^1\big(x^2-2x^3+x^4\big)\,dx=12\Big(\frac13-\frac12+\frac15\Big)=\frac25 .$$
#
# $E[\xi\eta]$ — по совместной плотности с пределами шага 1: внутренний интеграл $\int_0^{1-x}y^2dy=\frac{(1-x)^3}3$, затем раскрываем куб:
#
# $$E[\xi\eta]=\int_0^1\!\!\int_0^{1-x}24x^2y^2\,dy\,dx=8\int_0^1x^2(1-x)^3dx=8\Big(\frac13-\frac34+\frac35-\frac16\Big)=8\cdot\frac1{60}=\frac2{15}.$$
#
# $$\operatorname{cov}(\xi,\eta)=\frac2{15}-\frac4{25}=-\frac2{75}\approx-0{,}027 .$$
#
# Знак: доли делят общую массу, $\xi+\eta\le1$, и чем больше меди, тем меньше места никелю.
#
# **Шаг 4. Технолог неправ.** $\operatorname{cov}\ne0\Rightarrow$ зависимы.
#
# Ошибка технолога: на всей плоскости $\rho=24xy\cdot\mathbf 1_{T_1}(x,y)$, а индикатор треугольника не раскладывается (п. 4 теории).


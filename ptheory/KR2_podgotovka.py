# ## Задача 4. Функция от дискретной случайной величины: склейка, ковариация, зависимость

# %% [markdown]
# ### Теория
#
# Пусть $P(\xi=x_k)=p_k$, а $\eta=g(\xi)$.
#
# **1. Нормировка параметрического ряда.** Если вероятности заданы с точностью до множителя, $p_k=c\,a_k$, то из $\sum_k p_k=1$
#
# $$
# c=\frac{1}{\sum_k a_k}.
# $$
#
# Для бесконечного носителя нужна сумма ряда, чаще всего геометрической прогрессии: $\sum_{k\ge0}q^k=\frac1{1-q}$ при $|q|<1$. Если неизвестных два, второе уравнение даёт дополнительное условие, например заданное среднее.
#
# **2. Ряд $\eta$ и склейка.** Значения $\eta$ — это числа $g(x_k)$, а по аддитивности
#
# $$
# P(\eta=y)=\sum_{k:\;g(x_k)=y}p_k.
# $$
#
# Если $g$ принимает одно значение в нескольких точках носителя, эти точки **склеиваются**, а их вероятности **складываются**. Повторов в ряде быть не должно: объедини их и упорядочь значения. Проверка: сумма вероятностей снова 1. Функция распределения $F_\eta(y)=P(\eta\le y)$ ступенчатая, как в задаче 1: в каждом значении прыжок на его вероятность. Неравенство нестрогое, поэтому в самой точке скачка уже стоит верхнее значение (непрерывность справа), и промежутки пишут в виде $y_j\le y<y_{j+1}$.
#
# **3. LOTUS и дисперсия.** Для среднего ряд $\eta$ не нужен: $E\,g(\xi)=\sum_k g(x_k)\,p_k$ (при бесконечном носителе — если ряд сходится абсолютно). Почему: подставим п. 2 в определение среднего — получатся те же слагаемые, сгруппированные по значению $g$:
#
# $$
# \sum_j y_j\sum_{k:\,g(x_k)=y_j}p_k=\sum_j\ \sum_{k:\,g(x_k)=y_j}g(x_k)\,p_k=\sum_k g(x_k)\,p_k.
# $$
#
# Значит, склейка на среднее не влияет, но обязательна для ряда и функции распределения. Дисперсия: $\operatorname{Var}\eta=E\eta^2-(E\eta)^2$, где второй момент — снова LOTUS для функции $g^2$.
#
# **4. Совместная таблица $(\xi,\eta)$.** Её клетки — вероятности $p_{ij}=P(\xi=x_i,\ \eta=y_j)$, суммы по строкам и столбцам дают ряды обеих величин (маргиналы). Когда $\eta$ — функция $\xi$, значение $\xi$ уже определяет $\eta$:
#
# $$
# P(\xi=x_i,\ \eta=y_j)=p_i\ \text{ при } y_j=g(x_i),\qquad 0\ \text{ иначе}.
# $$
#
# Таблица **вырождена**: в каждой строке одна ненулевая клетка, а суммы столбцов — ряд из п. 2 (проверка склейки).
#
# **5. Ковариация и корреляция.** $\operatorname{cov}(\xi,\eta)=E[\xi\eta]-E\xi\,E\eta$, где $E[\xi\eta]=\sum_{i,j}x_iy_jp_{ij}$. По вырожденной таблице это LOTUS для функции $x\,g(x)$ одной величины. Коэффициент корреляции
#
# $$
# \rho(\xi,\eta)=\frac{\operatorname{cov}(\xi,\eta)}{\sqrt{\operatorname{Var}\xi\cdot\operatorname{Var}\eta}}\in[-1,1].
# $$
#
# **6. Независимость.** Дискретные величины независимы, если $p_{ij}=P(\xi=x_i)\,P(\eta=y_j)$ **во всех** клетках. Для зависимости хватает одной клетки, где равенство нарушено; удобнее всего нулевая клетка при ненулевых маргиналах. При независимости двойная сумма распадается в произведение: $E[\xi\eta]=\sum_{i,j}x_iy_j\,P(\xi=x_i)P(\eta=y_j)=E\xi\cdot E\eta$, то есть ковариация равна нулю. Поэтому **ненулевая ковариация доказывает зависимость, а нулевая независимости не гарантирует** (примеры — в задаче 2 и в углублении ниже).

# %% [markdown]
# ### Условие
#
# Кофейня каждое утро заказывает 2 торта. Число покупателей $\xi$, пришедших за тортом за день, принимает значения $0,1,2,3,4$, причём
#
# $$
# P(\xi=k)=c\,(k+1),\qquad k=0,1,2,3,4.
# $$
#
# Каждый покупатель берёт один торт. «Промах» дня $\eta=|\xi-2|$ — сколько тортов осталось или сколько покупателей ушли без торта. Найди:
# 1. константу $c$;
# 2. ряд и функцию распределения промаха, его среднее и дисперсию;
# 3. совместную таблицу $(\xi,\eta)$, ковариацию $\operatorname{cov}(\xi,\eta)$ и коэффициент корреляции;
# 4. зависимы ли спрос и промах? Обоснуй двумя способами.

# %% [markdown]
# ### Решение
#
# **Шаг 1. Нормировка.** $c\,(1+2+3+4+5)=15c=1$, откуда $c=\frac1{15}$. Удобно считать в пятнадцатых: $P(\xi=k)=\frac{k+1}{15}$.
#
# **Шаг 2. Склейка.** При спросе 0, 1, 2, 3, 4 промах равен 2, 1, 0, 1, 2. Значение 1 дают спрос 1 и 3, значение 2 — спрос 0 и 4. Складываем их вероятности:
#
# $$
# P(\eta=0)=\frac{3}{15}=\frac15,\qquad P(\eta=1)=\frac{2+4}{15}=\frac25,\qquad P(\eta=2)=\frac{1+5}{15}=\frac25.
# $$
#
# Сумма равна 1 — склейка верна. Функция распределения — накопленные суммы этих вероятностей:
#
# $$
# F_\eta(y)=0\ (y<0),\quad \tfrac15\ (0\le y<1),\quad \tfrac35\ (1\le y<2),\quad 1\ (y\ge2).
# $$
#
# **Шаг 3. Среднее и дисперсия промаха.** По ряду из шага 2:
#
# $$
# E\eta=1\cdot\frac25+2\cdot\frac25=\frac65,\qquad E\eta^2=1\cdot\frac25+4\cdot\frac25=2,\qquad \operatorname{Var}\eta=2-\frac{36}{25}=\frac{14}{25}.
# $$
#
# Сверка по LOTUS, без склейки: $E\eta=\frac{2\cdot1+1\cdot2+0\cdot3+1\cdot4+2\cdot5}{15}=\frac{18}{15}=\frac65$ — то же самое.
#
# **Шаг 4. Совместная таблица.** По п. 4 теории в строке $\xi=k$ единственная ненулевая клетка стоит в столбце $|k-2|$ (числа — в пятнадцатых):
#
# | $\xi\ \backslash\ \eta$ | 0 | 1 | 2 |
# |---|---|---|---|
# | 0 | 0 | 0 | 1 |
# | 1 | 0 | 2 | 0 |
# | 2 | 3 | 0 | 0 |
# | 3 | 0 | 4 | 0 |
# | 4 | 0 | 0 | 5 |
#
# Суммы столбцов 3, 6, 6 совпадают с рядом из шага 2.
#
# **Шаг 5. Ковариация.** $E\xi=\frac{0+2+6+12+20}{15}=\frac83$. Произведение $\xi\eta$ — функция $\xi$, складываем $k\cdot|k-2|\cdot(k+1)$ по строкам таблицы:
#
# $$
# E[\xi\eta]=\frac{0+1\cdot1\cdot2+0+3\cdot1\cdot4+4\cdot2\cdot5}{15}=\frac{54}{15}=\frac{18}5,\qquad \operatorname{cov}(\xi,\eta)=\frac{18}5-\frac83\cdot\frac65=\frac25.
# $$
#
# **Шаг 6. Корреляция.** Сдвиг не меняет дисперсию, а $(\xi-2)^2=\eta^2$ — второй момент уже есть в шаге 3:
#
# $$
# \operatorname{Var}\xi=\operatorname{Var}(\xi-2)=E\eta^2-(E\xi-2)^2=2-\frac49=\frac{14}9,\qquad \rho=\frac{2/5}{\sqrt{\frac{14}9\cdot\frac{14}{25}}}=\frac{2/5}{14/15}=\frac37.
# $$
#
# **Шаг 7. Зависимость.** Первый способ: $\operatorname{cov}\ne0$, значит, величины зависимы. Второй — одна клетка таблицы: $P(\xi=2,\ \eta=1)=0$, а $P(\xi=2)\,P(\eta=1)=\frac15\cdot\frac25=\frac2{25}\ne0$.
#
# Промах — функция спроса (зависимость функциональная), но $\rho=\frac37$ далеко от 1: корреляция измеряет только линейную связь, а промах убывает при спросе до 2 и растёт после. Знак плюс: правая ветка, где промах растёт, вероятнее ($\frac35$ против $\frac15$).


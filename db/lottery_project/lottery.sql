-- Физическая модель БД лотерейного оператора (PostgreSQL 14+).
-- Запуск из каталога со скриптом: psql -v ON_ERROR_STOP=1 -f lottery.sql
-- Скрипт пересоздаёт таблицы, затем грузит CSV из каталога data.

BEGIN;

DROP TABLE IF EXISTS prizes, ticket_numbers, tickets, draw_numbers, draws, lottery_terms, lotteries, users CASCADE;

-- EXCLUDE по (lottery_id, диапазон дат) требует btree_gist
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE users (
    user_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(254) NOT NULL,
    full_name     varchar(200) NOT NULL,
    phone         varchar(32),
    birth_date    date,
    city          varchar(100),
    registered_at timestamptz  NOT NULL,
    status        varchar(16)  NOT NULL DEFAULT 'active',
    CONSTRAINT users_status_check CHECK (status IN ('active', 'blocked', 'deleted')),
    CONSTRAINT users_email_format_check CHECK (email LIKE '_%@_%._%')
);
-- Почта уникальна без учёта регистра: в анкетах встречается и Ivanov@Mail.ru, и ivanov@mail.ru
CREATE UNIQUE INDEX users_email_lower_key ON users (lower(email));

CREATE TABLE lotteries (
    lottery_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           varchar(16)  NOT NULL UNIQUE,
    name           varchar(100) NOT NULL,
    numbers_total  smallint     NOT NULL,
    numbers_picked smallint     NOT NULL,
    launched_at    timestamptz  NOT NULL,
    closed_at      timestamptz,
    CONSTRAINT lotteries_numbers_check CHECK (numbers_picked BETWEEN 1 AND numbers_total - 1 AND numbers_total <= 99),
    CONSTRAINT lotteries_period_check CHECK (closed_at IS NULL OR closed_at > launched_at)
);

-- SCD2: условия лотереи (цена билета, доля выручки в джекпот) версионируются по времени.
-- Открытая версия имеет end_dttm = '9999-12-31 00:00:00+00' (полночь: в часовом поясе MSK значение не уходит
-- за 9999 год, иначе драйверы вроде psycopg2 не могут его прочитать), интервал [start_dttm, end_dttm).
CREATE TABLE lottery_terms (
    terms_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lottery_id    integer       NOT NULL REFERENCES lotteries,
    ticket_price  numeric(10, 2) NOT NULL,
    jackpot_share numeric(4, 3) NOT NULL,
    start_dttm    timestamptz   NOT NULL,
    end_dttm      timestamptz   NOT NULL DEFAULT '9999-12-31 00:00:00+00',
    CONSTRAINT lottery_terms_price_check CHECK (ticket_price > 0),
    CONSTRAINT lottery_terms_jackpot_share_check CHECK (jackpot_share BETWEEN 0 AND 1),
    CONSTRAINT lottery_terms_period_check CHECK (end_dttm > start_dttm),
    CONSTRAINT lottery_terms_no_overlap EXCLUDE USING gist (
        lottery_id WITH =,
        tstzrange(start_dttm, end_dttm) WITH &&
    )
);

CREATE TABLE draws (
    draw_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lottery_id   integer     NOT NULL REFERENCES lotteries,
    draw_number  integer     NOT NULL,
    scheduled_at timestamptz NOT NULL,
    drawn_at     timestamptz,
    status       varchar(16) NOT NULL DEFAULT 'scheduled',
    CONSTRAINT draws_lottery_number_key UNIQUE (lottery_id, draw_number),
    CONSTRAINT draws_status_check CHECK (status IN ('scheduled', 'completed', 'cancelled')),
    CONSTRAINT draws_drawn_at_check CHECK ((status = 'completed') = (drawn_at IS NOT NULL))
);

-- Выигрышная комбинация тиража: одно число на строку (1НФ вместо массива)
CREATE TABLE draw_numbers (
    draw_id bigint   NOT NULL REFERENCES draws ON DELETE CASCADE,
    number  smallint NOT NULL,
    PRIMARY KEY (draw_id, number),
    CONSTRAINT draw_numbers_range_check CHECK (number BETWEEN 1 AND 99)
);

CREATE TABLE tickets (
    ticket_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint        NOT NULL REFERENCES users,
    draw_id      bigint        NOT NULL REFERENCES draws,
    purchased_at timestamptz   NOT NULL,
    -- Фактически уплаченная сумма: может отличаться от цены по условиям из-за промо
    price_paid   numeric(10, 2) NOT NULL,
    channel      varchar(16)   NOT NULL,
    status       varchar(16)   NOT NULL DEFAULT 'sold',
    CONSTRAINT tickets_price_check CHECK (price_paid >= 0),
    CONSTRAINT tickets_channel_check CHECK (channel IN ('web', 'mobile', 'retail')),
    CONSTRAINT tickets_status_check CHECK (status IN ('sold', 'refunded'))
);
CREATE INDEX tickets_user_id_idx ON tickets (user_id);
CREATE INDEX tickets_draw_id_idx ON tickets (draw_id);

CREATE TABLE ticket_numbers (
    ticket_id bigint   NOT NULL REFERENCES tickets ON DELETE CASCADE,
    number    smallint NOT NULL,
    PRIMARY KEY (ticket_id, number),
    CONSTRAINT ticket_numbers_range_check CHECK (number BETWEEN 1 AND 99)
);

-- Не больше одного приза на билет: категорию определяет число совпадений
CREATE TABLE prizes (
    prize_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id     bigint        NOT NULL UNIQUE REFERENCES tickets,
    matched_count smallint      NOT NULL,
    amount        numeric(14, 2) NOT NULL,
    status        varchar(16)   NOT NULL DEFAULT 'pending',
    paid_at       timestamptz,
    CONSTRAINT prizes_matched_count_check CHECK (matched_count >= 1),
    CONSTRAINT prizes_amount_check CHECK (amount > 0),
    CONSTRAINT prizes_status_check CHECK (status IN ('pending', 'paid', 'expired')),
    CONSTRAINT prizes_paid_at_check CHECK ((status = 'paid') = (paid_at IS NOT NULL))
);

\copy users (user_id, email, full_name, phone, birth_date, city, registered_at, status) from 'data/users.csv' with (format csv, header true)
\copy lotteries (lottery_id, code, name, numbers_total, numbers_picked, launched_at, closed_at) from 'data/lotteries.csv' with (format csv, header true)
\copy lottery_terms (terms_id, lottery_id, ticket_price, jackpot_share, start_dttm, end_dttm) from 'data/lottery_terms.csv' with (format csv, header true)
\copy draws (draw_id, lottery_id, draw_number, scheduled_at, drawn_at, status) from 'data/draws.csv' with (format csv, header true)
\copy draw_numbers (draw_id, number) from 'data/draw_numbers.csv' with (format csv, header true)
\copy tickets (ticket_id, user_id, draw_id, purchased_at, price_paid, channel, status) from 'data/tickets.csv' with (format csv, header true)
\copy ticket_numbers (ticket_id, number) from 'data/ticket_numbers.csv' with (format csv, header true)
\copy prizes (prize_id, ticket_id, matched_count, amount, status, paid_at) from 'data/prizes.csv' with (format csv, header true)

-- Ключи пришли из CSV явно, поэтому identity-последовательности сдвигаются за максимум
SELECT setval(pg_get_serial_sequence('users', 'user_id'), max(user_id)) FROM users;
SELECT setval(pg_get_serial_sequence('lotteries', 'lottery_id'), max(lottery_id)) FROM lotteries;
SELECT setval(pg_get_serial_sequence('lottery_terms', 'terms_id'), max(terms_id)) FROM lottery_terms;
SELECT setval(pg_get_serial_sequence('draws', 'draw_id'), max(draw_id)) FROM draws;
SELECT setval(pg_get_serial_sequence('tickets', 'ticket_id'), max(ticket_id)) FROM tickets;
SELECT setval(pg_get_serial_sequence('prizes', 'prize_id'), max(prize_id)) FROM prizes;

ANALYZE users, lotteries, lottery_terms, draws, draw_numbers, tickets, ticket_numbers, prizes;

COMMIT;
